#!/usr/bin/env node

import { execFileSync } from 'node:child_process';
import {
  existsSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  writeFileSync,
} from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const apiRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const workspaceRoot = resolve(apiRoot, '..');
const entitiesRoot = join(workspaceRoot, 'ifs-standards', 'src', 'entities');
const prismaSchemaPath = join(apiRoot, 'prisma', 'schema.prisma');
const entityRelationsPath = join(
  workspaceRoot,
  'ifs-standards',
  'scripts',
  'entity-relations.json',
);
const generateDtosPath = join(apiRoot, 'scripts', 'generate-dtos.mjs');
const generatedMarker = '// Generated by scripts/generate-resource.mjs.';
const generatedResourcesModulePath = join(
  apiRoot,
  'src',
  'generated-resources.module.ts',
);

function usage(message) {
  if (message) console.error(`Error: ${message}\n`);
  console.error(
    'Usage: pnpm --filter prototype-api resource:generate <entity-name> [--skip-format]',
  );
  process.exitCode = message ? 1 : 0;
}

function kebabCase(value) {
  return value
    .replace(/([a-z0-9])([A-Z])/g, '$1-$2')
    .replace(/[^A-Za-z0-9]+/g, '-')
    .replace(/^-|-$/g, '')
    .toLowerCase();
}

function lowerCamelCase(value) {
  return value[0].toLowerCase() + value.slice(1);
}

function pluralRoute(entityName) {
  if (entityName.endsWith('y') && !/[aeiou]y$/.test(entityName)) {
    return `${entityName.slice(0, -1)}ies`;
  }
  if (/(s|x|z|ch|sh)$/.test(entityName)) return `${entityName}es`;
  return `${entityName}s`;
}

function readEntity(entityInput) {
  if (!entityInput || !/^[A-Za-z][A-Za-z0-9-]*$/.test(entityInput)) {
    throw new Error(`Invalid entity name: ${entityInput || '(missing)'}`);
  }

  const entityName = kebabCase(entityInput);
  const schemaPath = join(
    entitiesRoot,
    entityName,
    `${entityName}.schema.json`,
  );
  if (!existsSync(schemaPath)) {
    throw new Error(
      `Entity "${entityInput}" is not defined in IFS standards (expected ${schemaPath}).`,
    );
  }

  let schema;
  try {
    schema = JSON.parse(readFileSync(schemaPath, 'utf8'));
  } catch (error) {
    throw new Error(
      `Could not read entity schema ${schemaPath}: ${error instanceof Error ? error.message : String(error)}`,
    );
  }

  if (
    schema.type !== 'object' ||
    typeof schema.title !== 'string' ||
    !/^[A-Za-z][A-Za-z0-9]*$/.test(schema.title)
  ) {
    throw new Error(
      `Entity schema ${schemaPath} must define an object with a valid title.`,
    );
  }

  return { entityName, modelName: schema.title, schemaPath };
}

function expectedDtos(entityName, modelName) {
  const dtoRoot = join(apiRoot, 'src', entityName, 'dto');
  return [
    {
      path: join(dtoRoot, `create-${entityName}.dto.ts`),
      className: `Create${modelName}Dto`,
    },
    {
      path: join(dtoRoot, `update-${entityName}.dto.ts`),
      className: `Update${modelName}Dto`,
    },
    {
      path: join(dtoRoot, `${entityName}-response.dto.ts`),
      className: `${modelName}ResponseDto`,
    },
  ];
}

function missingDtos(entityName, modelName) {
  return expectedDtos(entityName, modelName).filter(({ path, className }) => {
    if (!existsSync(path)) return true;
    const source = readFileSync(path, 'utf8');
    return !new RegExp(`export\\s+class\\s+${className}\\b`).test(source);
  });
}

function ensureDtos(entityName, modelName) {
  let missing = missingDtos(entityName, modelName);
  if (!missing.length) return false;

  console.log(
    `Missing DTOs for ${modelName}; generating DTO artifacts for all IFS entities...`,
  );
  execFileSync(process.execPath, [generateDtosPath], {
    cwd: apiRoot,
    stdio: 'inherit',
  });

  missing = missingDtos(entityName, modelName);
  if (missing.length) {
    throw new Error(
      `DTO generation completed but these DTOs are still missing or invalid: ${missing
        .map(({ path }) => relative(workspaceRoot, path))
        .join(', ')}`,
    );
  }
  return true;
}

function assertPrismaModel(modelName) {
  if (!existsSync(prismaSchemaPath)) {
    throw new Error(`Prisma schema not found: ${prismaSchemaPath}`);
  }
  const prismaSchema = readFileSync(prismaSchemaPath, 'utf8');
  if (!new RegExp(`(^|\\n)model\\s+${modelName}\\s*\\{`).test(prismaSchema)) {
    throw new Error(
      `Prisma model ${modelName} is missing. Run the DTO generator before generating its service.`,
    );
  }
}

function readEntityRelations(modelName) {
  let metadata;
  try {
    metadata = JSON.parse(readFileSync(entityRelationsPath, 'utf8'));
  } catch (error) {
    throw new Error(
      `Could not read entity relations ${entityRelationsPath}: ${error instanceof Error ? error.message : String(error)}`,
    );
  }

  const relations =
    metadata && typeof metadata === 'object' ? metadata[modelName] : undefined;
  if (!Array.isArray(relations)) {
    throw new Error(`Entity relations metadata is missing ${modelName}.`);
  }

  const invalidRelation = relations.find(
    (relation) =>
      !relation ||
      typeof relation.property !== 'string' ||
      !/^[A-Za-z_][A-Za-z0-9_]*$/.test(relation.property) ||
      typeof relation.type !== 'string',
  );
  if (invalidRelation) {
    throw new Error(`Entity relations metadata for ${modelName} is invalid.`);
  }

  return [...new Set(relations.map(({ property }) => property))];
}

function renderService(entityName, modelName, relations) {
  const delegateName = lowerCamelCase(modelName);
  const relationsName = `${delegateName}Relations`;
  const relationsDeclaration = relations.length
    ? `\nconst ${relationsName} = {\n${relations.map((relation) => `  ${relation}: true,`).join('\n')}\n} as const;\n`
    : '';
  const includeRelations = relations.length
    ? `\n      include: ${relationsName},`
    : '';
  const findManyArguments = relations.length
    ? `{${includeRelations}\n    }`
    : '';
  return `${generatedMarker}
import { Injectable } from '@nestjs/common';
import type { Prisma } from '../generated/prisma/client.js';
import { PrismaService } from '../prisma/prisma.service.js';
import { Create${modelName}Dto } from './dto/create-${entityName}.dto.js';
import { ${modelName}ResponseDto } from './dto/${entityName}-response.dto.js';
import { Update${modelName}Dto } from './dto/update-${entityName}.dto.js';
${relationsDeclaration}
@Injectable()
export class ${modelName}Service {
  constructor(private readonly prisma: PrismaService) {}

  create(data: Create${modelName}Dto): Promise<${modelName}ResponseDto> {
    return this.prisma.${delegateName}.create({
      data: data as unknown as Prisma.${modelName}CreateInput,${includeRelations}
    }) as unknown as Promise<${modelName}ResponseDto>;
  }

  findAll(): Promise<${modelName}ResponseDto[]> {
    return this.prisma.${delegateName}.findMany(${findManyArguments}) as unknown as Promise<
      ${modelName}ResponseDto[]
    >;
  }

  findOne(id: string): Promise<${modelName}ResponseDto | null> {
    return this.prisma.${delegateName}.findUnique({
      where: { id },${includeRelations}
    }) as unknown as Promise<${modelName}ResponseDto | null>;
  }

  update(id: string, data: Update${modelName}Dto): Promise<${modelName}ResponseDto> {
    return this.prisma.${delegateName}.update({
      where: { id },
      data: data as unknown as Prisma.${modelName}UpdateInput,${includeRelations}
    }) as unknown as Promise<${modelName}ResponseDto>;
  }

  remove(id: string): Promise<${modelName}ResponseDto> {
    return this.prisma.${delegateName}.delete({
      where: { id },${includeRelations}
    }) as unknown as Promise<${modelName}ResponseDto>;
  }
}
`;
}

function renderController(entityName, modelName) {
  const serviceName = lowerCamelCase(modelName);
  const route = pluralRoute(entityName);
  return `${generatedMarker}
import {
  Body,
  Controller,
  Delete,
  Get,
  HttpCode,
  HttpStatus,
  NotFoundException,
  Param,
  Patch,
  Post,
} from '@nestjs/common';
import {
  ApiBody,
  ApiCreatedResponse,
  ApiNoContentResponse,
  ApiNotFoundResponse,
  ApiOkResponse,
  ApiOperation,
  ApiParam,
  ApiTags,
} from '@nestjs/swagger';
import { Create${modelName}Dto } from './dto/create-${entityName}.dto.js';
import { ${modelName}ResponseDto } from './dto/${entityName}-response.dto.js';
import { Update${modelName}Dto } from './dto/update-${entityName}.dto.js';
import { ${modelName}Service } from './${entityName}.service.js';

@ApiTags('${route}')
@Controller('${route}')
export class ${modelName}Controller {
  constructor(private readonly ${serviceName}Service: ${modelName}Service) {}

  @Post()
  @ApiOperation({ operationId: 'create${modelName}', summary: 'Create a ${modelName}.' })
  @ApiBody({ type: Create${modelName}Dto })
  @ApiCreatedResponse({ type: ${modelName}ResponseDto })
  create(@Body() data: Create${modelName}Dto): Promise<${modelName}ResponseDto> {
    return this.${serviceName}Service.create(data);
  }

  @Get()
  @ApiOperation({ operationId: 'list${modelName}s', summary: 'List ${modelName} records.' })
  @ApiOkResponse({ type: ${modelName}ResponseDto, isArray: true })
  findAll(): Promise<${modelName}ResponseDto[]> {
    return this.${serviceName}Service.findAll();
  }

  @Get(':id')
  @ApiOperation({ operationId: 'get${modelName}', summary: 'Get a ${modelName} by ID.' })
  @ApiParam({ name: 'id', type: String, description: '${modelName} ID.' })
  @ApiOkResponse({ type: ${modelName}ResponseDto })
  @ApiNotFoundResponse({ description: '${modelName} not found.' })
  async findOne(@Param('id') id: string): Promise<${modelName}ResponseDto> {
    const result = await this.${serviceName}Service.findOne(id);
    if (!result) throw new NotFoundException('${modelName} not found.');
    return result;
  }

  @Patch(':id')
  @ApiOperation({ operationId: 'update${modelName}', summary: 'Update a ${modelName}.' })
  @ApiParam({ name: 'id', type: String, description: '${modelName} ID.' })
  @ApiBody({ type: Update${modelName}Dto })
  @ApiOkResponse({ type: ${modelName}ResponseDto })
  @ApiNotFoundResponse({ description: '${modelName} not found.' })
  update(
    @Param('id') id: string,
    @Body() data: Update${modelName}Dto,
  ): Promise<${modelName}ResponseDto> {
    return this.${serviceName}Service.update(id, data);
  }

  @Delete(':id')
  @HttpCode(HttpStatus.NO_CONTENT)
  @ApiOperation({ operationId: 'delete${modelName}', summary: 'Delete a ${modelName}.' })
  @ApiParam({ name: 'id', type: String, description: '${modelName} ID.' })
  @ApiNoContentResponse({ description: '${modelName} deleted.' })
  @ApiNotFoundResponse({ description: '${modelName} not found.' })
  async remove(@Param('id') id: string): Promise<void> {
    await this.${serviceName}Service.remove(id);
  }
}
`;
}

function renderModule(entityName, modelName) {
  return `${generatedMarker}
import { Module } from '@nestjs/common';
import { ${modelName}Controller } from './${entityName}.controller.js';
import { ${modelName}Service } from './${entityName}.service.js';

@Module({
  controllers: [${modelName}Controller],
  providers: [${modelName}Service],
})
export class ${modelName}Module {}
`;
}

function generatedResourceModules() {
  const sourceRoot = join(apiRoot, 'src');
  if (!existsSync(sourceRoot)) return [];

  return readdirSync(sourceRoot, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .flatMap((entry) => {
      const modulePath = join(
        sourceRoot,
        entry.name,
        `${entry.name}.module.ts`,
      );
      if (!existsSync(modulePath)) return [];
      const source = readFileSync(modulePath, 'utf8');
      if (!source.startsWith(generatedMarker)) return [];
      const match = /export class ([A-Za-z][A-Za-z0-9]*)Module\s*\{\}/.exec(
        source,
      );
      return match
        ? [{ entityName: entry.name, modelName: match[1], modulePath }]
        : [];
    })
    .sort((left, right) => left.entityName.localeCompare(right.entityName));
}

function renderGeneratedResourcesModule(resources) {
  return `${generatedMarker}
import { Module } from '@nestjs/common';
${resources
  .map(
    ({ entityName, modelName }) =>
      `import { ${modelName}Module } from './${entityName}/${entityName}.module.js';`,
  )
  .join('\n')}

@Module({
  imports: [${resources.map(({ modelName }) => `${modelName}Module`).join(', ')}],
})
export class GeneratedResourcesModule {}
`;
}

export function generateService(entityInput, options = {}) {
  const { entityName, modelName, schemaPath } = readEntity(entityInput);
  const generatedDtos = ensureDtos(entityName, modelName);
  assertPrismaModel(modelName);
  const relations = readEntityRelations(modelName);

  const serviceDirectory = join(apiRoot, 'src', entityName);
  const generatedFiles = [
    {
      kind: 'service',
      path: join(serviceDirectory, `${entityName}.service.ts`),
      source: renderService(entityName, modelName, relations),
    },
    {
      kind: 'controller',
      path: join(serviceDirectory, `${entityName}.controller.ts`),
      source: renderController(entityName, modelName),
    },
    {
      kind: 'module',
      path: join(serviceDirectory, `${entityName}.module.ts`),
      source: renderModule(entityName, modelName),
    },
  ];

  for (const file of generatedFiles) {
    if (!existsSync(file.path)) continue;
    const existing = readFileSync(file.path, 'utf8');
    if (!existing.startsWith(generatedMarker)) {
      throw new Error(
        `Refusing to overwrite ${file.kind} not managed by this generator: ${file.path}`,
      );
    }
  }

  if (existsSync(generatedResourcesModulePath)) {
    const registry = readFileSync(generatedResourcesModulePath, 'utf8');
    if (!registry.startsWith(generatedMarker)) {
      throw new Error(
        `Refusing to overwrite resource registry not managed by this generator: ${generatedResourcesModulePath}`,
      );
    }
  }

  mkdirSync(serviceDirectory, { recursive: true });
  for (const file of generatedFiles) writeFileSync(file.path, file.source);
  writeFileSync(
    generatedResourcesModulePath,
    renderGeneratedResourcesModule(generatedResourceModules()),
  );

  if (!options.skipFormat) {
    execFileSync(
      'pnpm',
      [
        'exec',
        'prettier',
        '--write',
        ...generatedFiles.map((file) => file.path),
        generatedResourcesModulePath,
      ],
      { cwd: apiRoot, stdio: 'inherit' },
    );
  }

  return {
    entityName,
    modelName,
    schemaPath,
    servicePath: generatedFiles[0].path,
    generatedFiles: [
      ...generatedFiles.map((file) => file.path),
      generatedResourcesModulePath,
    ],
    generatedDtos,
  };
}

function main() {
  const args = process.argv.slice(2);
  if (args.includes('--help') || args.includes('-h')) return usage();

  const allowedFlags = new Set(['--skip-format']);
  const unknownFlag = args.find(
    (arg) => arg.startsWith('-') && !allowedFlags.has(arg),
  );
  if (unknownFlag) return usage(`Unknown option: ${unknownFlag}`);

  const positional = args.filter((arg) => !arg.startsWith('--'));
  if (positional.length !== 1)
    return usage('Expected exactly one entity name.');

  try {
    const result = generateService(positional[0], {
      skipFormat: args.includes('--skip-format'),
    });
    if (result.generatedDtos) console.log('Generated missing DTOs.');
    console.log(
      `Generated ${result.modelName} resource in ${relative(workspaceRoot, dirname(result.servicePath))}`,
    );
  } catch (error) {
    console.error(error instanceof Error ? error.message : String(error));
    process.exitCode = 1;
  }
}

if (
  process.argv[1] &&
  resolve(process.argv[1]) === fileURLToPath(import.meta.url)
)
  main();
